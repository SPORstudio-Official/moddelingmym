#!/usr/bin/env python3
"""Generate src/font_data.h : a 1-bit bitmap font atlas (6x9 cells) from DejaVu Sans Mono Bold."""
from PIL import Image, ImageDraw, ImageFont
import sys

SIZE = 9
CW, CH = 6, 10            # cell size in pixels
BASELINE = 7             # rows above baseline
THRESH = 95
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"

def main(out):
    font = ImageFont.truetype(FONT, SIZE)
    first, last = 32, 126
    n = last - first + 1
    glyphs = []
    for code in range(first, last + 1):
        ch = chr(code)
        img = Image.new("L", (CW, CH + 4), 0)
        d = ImageDraw.Draw(img)
        d.text((0, BASELINE), ch, font=font, fill=255, anchor="ls")
        px = img.load()
        rows = []
        for y in range(CH):
            bits = 0
            for x in range(CW):
                if px[x, y] > THRESH:
                    bits |= (1 << (CW - 1 - x))
            rows.append(bits)
        # trim: space char must stay blank
        glyphs.append(rows)

    with open(out, "w") as f:
        f.write("/* generated by tools/gen_font.py -- do not edit */\n")
        f.write("#ifndef FONT_DATA_H\n#define FONT_DATA_H\n")
        f.write("#define FONT_W %d\n#define FONT_H %d\n#define FONT_FIRST %d\n#define FONT_COUNT %d\n"
                % (CW, CH, first, n))
        f.write("static const unsigned char font_glyphs[%d][%d] = {\n" % (n, CH))
        for rows in glyphs:
            f.write("  {" + ",".join("0x%02x" % r for r in rows) + "},\n")
        f.write("};\n#endif\n")
    # preview
    prev = Image.new("L", (n * CW + 8, CH + 40), 0)
    d = ImageDraw.Draw(prev)
    for i, rows in enumerate(glyphs):
        for y, bits in enumerate(rows):
            for x in range(CW):
                if bits & (1 << (CW - 1 - x)):
                    d.point((4 + i * CW + x, 4 + y), 255)
    prev.save("/tmp/font_preview.png")
    print("wrote", out, "glyphs", n)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/font_data.h")
