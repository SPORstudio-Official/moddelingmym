#!/usr/bin/env python3
"""
genfont.py -- Procedural font atlas generator for AetherOS.

Rasterizes DejaVu faces into packed 1bpp glyph bitmaps (4x4 supersampled) and
emits them as a C header of static byte arrays, so the final executable has
zero external font assets.

  * CP437 / ASCII 8x16 terminal font   (DejaVu Sans Mono Bold)
  * UI proportional font, 3 sizes      (DejaVu Sans 12/14/17 px)

Usage:  python3 tools/genfont.py > dev/font_data.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

MONO = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

SS = 4  # supersample factor
TH = 52   # coverage threshold (percent)

TERM_W, TERM_H = 8, 16
TERM_PX = 13.0  # design size of mono glyphs
UI_SIZES = [12.0, 14.0, 17.0]

# CP437 glyphs that get remapped into the terminal renderer's extended table.
CP437_EXTRA = ("\u00b0\u00b1\u00b2\u2591\u2592\u2593\u2502\u2524\u2561\u2562\u2556\u2555"
               "\u2563\u2551\u2557\u255d\u255c\u255b\u2510\u2514\u2534\u252c\u251c\u2500"
               "\u253c\u255e\u255f\u255a\u2554\u2569\u2566\u2560\u2550\u256c\u2594\u2580"
               "\u259d\u2598\u258c\u2590\u2584\u2588\u03b1\u00df\u0393\u03c0\u03a3\u03c3"
               "\u00b5\u03c4\u03a6\u0398\u03a9\u03b4\u221e\u03c6\u03b5\u2229\u2261\u00b1"
               "\u2265\u2264\u2320\u2321\u00f7\u2248\u00b0\u2219\u00b7\u221a\u207f\u00b2"
               "\u25a0\u00a0\u2191\u2193\u2190\u2192\u25b6\u25c0\u2713\u2717")


def render(ch, path, px, cw, ch_h, bold=False):
    """Rasterize one glyph into a cw x ch_h 1bpp bitmap (list of ints, row-major
    bitmask MSB=left). Text is drawn SS times larger then box-filtered."""
    scale = SS
    img = Image.new("L", (cw * scale, ch_h * scale), 0)
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(path, int(round(px * scale)))
    # baseline such that cap height sits nicely inside the cell
    asc, desc = font.getmetrics()
    base_y = ch_h * scale - int(round(1.0 * scale))
    x = 0
    if cw > 9:  # proportional: small left bearing
        x = int(round(0.5 * scale))
    try:
        d.text((x, base_y), ch, fill=255, font=font, anchor="ls")
        if bold:
            d.text((x + int(0.6 * scale), base_y), ch, fill=255, font=font, anchor="ls")
    except Exception:
        pass
    out = []
    tot = scale * scale
    for yy in range(ch_h):
        row = 0
        for xx in range(cw):
            acc = 0
            for sy in range(scale):
                for sx in range(scale):
                    if img.getpixel((xx * scale + sx, yy * scale + sy)) > 96:
                        acc += 1
            if acc * 100 >= tot * TH:
                row |= 1 << (cw - 1 - xx)
        out.append(row)
    return out


def emit(name, data, typ="unsigned char", per=16):
    print(f"static const {typ} {name}[{len(data)}] = {{")
    for i in range(0, len(data), per):
        print("    " + ",".join("0x%02X" % b for b in data[i:i + per]) + ",")
    print("};")


def main():
    print("/* AUTO-GENERATED by tools/genfont.py -- do not edit by hand. */")
    print("#ifndef AETHER_FONT_DATA_H")
    print("#define AETHER_FONT_DATA_H")

    # ---------------- terminal monospace font ---------------------------
    chars = [chr(c) for c in range(0x20, 0x7F)] + list(CP437_EXTRA)
    flat = []
    for ch in chars:
        flat.extend(render(ch, MONO, TERM_PX, TERM_W, TERM_H))
    print(f"#define FONT_TERM_W {TERM_W}")
    print(f"#define FONT_TERM_H {TERM_H}")
    print(f"#define FONT_TERM_ASCII 95")
    print(f"#define FONT_TERM_COUNT {len(chars)}")
    emit("g_font_term", flat, "unsigned short", 12)
    print("static const unsigned int g_font_term_uni[FONT_TERM_COUNT - FONT_TERM_ASCII] = {")
    print("    " + ",".join("0x%04X" % ord(c) for c in CP437_EXTRA) + ",")
    print("};")

    # ---------------- UI proportional fonts -----------------------------
    for si, size in enumerate(UI_SIZES):
        font = ImageFont.truetype(SANS, int(round(size)))
        adv = [max(1, int(round(font.getlength(chr(c))))) for c in range(0x20, 0x7F)]
        asc, desc = font.getmetrics()
        h = asc + desc
        w = max(adv) + 1
        bits = []
        for gi, c in enumerate(range(0x20, 0x7F)):
            g = render(chr(c), SANS, size, w, h)
            for y, row in enumerate(g):
                for x in range(w):
                    if row & (1 << (w - 1 - x)):
                        bits.append(gi * w * h + y * w + x)
        bitset = set(bits)
        packed = bytearray()
        cur = nb = 0
        for i in range(w * h * 95):
            if i in bitset:
                cur |= 1 << nb
            nb += 1
            if nb == 8:
                packed.append(cur)
                cur = nb = 0
        if nb:
            packed.append(cur)
        print(f"#define UI_FONT_{si}_W {w}")
        print(f"#define UI_FONT_{si}_H {h}")
        print(f"#define UI_FONT_{si}_ASC {asc}")
        print(f"static const unsigned char g_ui_adv_{si}[95] = {{")
        for i in range(0, 95, 20):
            print("    " + ",".join(str(a) for a in adv[i:i + 20]) + ",")
        print("};")
        emit(f"g_ui_bits_{si}", packed, "unsigned char", 18)
    print("#endif")
    print(f"/* ui sizes {UI_SIZES} */", file=sys.stderr)


if __name__ == "__main__":
    main()
