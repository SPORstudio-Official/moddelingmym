#!/usr/bin/env python3
"""Resample the recorded tape audio to 16 kHz mono, split each tape into spoken
lines by silence, and emit src/audio_data.h (PCM + segment tables)."""
import wave, os, sys, json
import numpy as np

SR_OUT = 16000
TAPES = [
    ("tape1", 5), ("tape2", 6), ("tape3", 5), ("tape4", 6), ("tape5", 4),
]
ENTITY = [("entity", 3)]

def load(path):
    w = wave.open(path)
    sr = w.getframerate(); n = w.getnframes(); ch = w.getnchannels()
    raw = w.readframes(n)
    a = np.frombuffer(raw, dtype="<i2").astype(np.float32) / 32768.0
    if ch > 1:
        a = a.reshape(-1, ch).mean(axis=1)
    # linear resample
    if sr != SR_OUT:
        t = np.arange(int(len(a) * SR_OUT / sr)) * (sr / SR_OUT)
        a = np.interp(t, np.arange(len(a)), a).astype(np.float32)
    return a

def segments(a, expect, gap_s=0.16, rel=0.045):
    """Find speech chunks separated by silence."""
    win = int(0.02 * SR_OUT)
    env = np.abs(a[: len(a) // win * win]).reshape(-1, win).max(axis=1)
    peak = env.max()
    thr = max(peak * rel, 0.004)
    voiced = env > thr
    # close short holes
    hold = int(0.06 / 0.02)
    i = 0
    out = []
    in_run = False
    start = 0
    sil = 0
    for i, v in enumerate(voiced):
        if v:
            if not in_run:
                in_run = True
                start = i
            sil = 0
        else:
            if in_run:
                sil += 1
                if sil * 0.02 >= gap_s:
                    out.append((max(0, start * win - int(0.02 * SR_OUT)),
                                min(len(a), (i - sil + 1) * win + int(0.05 * SR_OUT))))
                    in_run = False
    if in_run:
        out.append((max(0, start * win - int(0.02 * SR_OUT)), len(a)))
    if len(out) != expect:
        return out, False
    return out, True

def main(src_dir, out_h):
    entries = []
    total = 0
    for name, expect in TAPES + ENTITY:
        p = os.path.join(src_dir, name + ".wav")
        a = load(p)
        a = a / max(1e-6, np.abs(a).max()) * 0.92
        segs = [(0, len(a))]
        print(f"{name}: {len(a)/SR_OUT:5.2f}s")
        entries.append((name, a, segs))
        total += len(a)

    with open(out_h, "w") as f:
        f.write("/* generated by tools/gen_audio.py -- do not edit */\n")
        f.write("#ifndef AUDIO_DATA_H\n#define AUDIO_DATA_H\n")
        f.write("#define AUDIO_SR %d\n" % SR_OUT)
        names = [e[0] for e in entries]
        f.write("#define AUDIO_CLIP_COUNT %d\n" % len(entries))
        f.write("enum { %s };\n" % ", ".join("CLIP_" + n.upper() for n in names))
        f.write("typedef struct { int start, len; } ClipSeg;\n")
        f.write("typedef struct { const short *pcm; int samples; const ClipSeg *segs; int nsegs; } AudioClip;\n")
        for name, a, segs in entries:
            pcm = np.clip(a * 32767, -32768, 32767).astype("<i2")
            f.write("static const short pcm_%s[%d] = {" % (name, len(pcm)))
            vals = pcm.tolist()
            for i in range(0, len(vals), 24):
                f.write("\n  " + ",".join(str(v) for v in vals[i:i+24]) + ",")
            f.write("\n};\n")
            f.write("static const ClipSeg seg_%s[%d] = {" % (name, max(1, len(segs))))
            if segs:
                f.write(",".join("{%d,%d}" % (s, e - s) for s, e in segs))
            else:
                f.write("{0,%d}" % len(a))
            f.write("};\n")
        f.write("static const AudioClip audio_clips[AUDIO_CLIP_COUNT] = {\n")
        for name, a, segs in entries:
            f.write("  { pcm_%s, %d, seg_%s, %d },\n" % (name, len(a), name, max(1, len(segs))))
        f.write("};\n#endif\n")
    print("wrote", out_h, "total samples", total, "->", round(total * 2 / 1e6, 2), "MB")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/audio",
         sys.argv[2] if len(sys.argv) > 2 else "src/audio_data.h")
