#!/usr/bin/env bash
# ============================================================================
# AE build script
#   Builds the standalone Windows executable from the modular dev/ sources.
#
#   The deliverable `aether_os.c` is a *single translation unit* produced by
#   concatenating the numbered modules below.  It has no external assets:
#   fonts and every other resource are static arrays inside the file.
#
#   Usage:
#     ./tools/build.sh              # -> AE.exe (Windows, static)
#     ./tools/build.sh --headless   # -> dev/aether_headless (Linux test build)
# ============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD
ZIG=${ZIG:-$HOME/.local/zig/zig}
[ -x "$ZIG" ] || { echo "zig not found at $ZIG -- run tools/setup_toolchain.sh" >&2; exit 1; }
# -nostdlib also strips the system include search path, so point the compiler at
# zig's bundled mingw headers explicitly (they are headers only -- nothing from
# the C runtime is linked).
ZIG_LIBC=$(dirname "$ZIG")/lib/libc/include/any-windows-any

MODULES=(
  dev/00_prelude.c
  dev/font_data.h
  dev/10_util.c
  dev/20_hal.c
  dev/30_irq.c
  dev/40_gfx.c
  dev/50_mm.c
  dev/60_vfs.c
  dev/65_proc.c
  dev/67_procfs.c
  dev/70_bytecode.c
  dev/75_registry.c
  dev/80_wm.c
  dev/85_app_sh.c
  dev/86_app_sysmon.c
  dev/87_app_explorer.c
  dev/88_app_edit.c
  dev/89_app_hexview.c
  dev/90_app_paint.c
  dev/91_app_settings.c
  dev/92_app_calc.c
  dev/93_app_console.c
  dev/74_html.c
  dev/94_app_browser.c
  dev/95_main.c
)

cat > aether_os.c <<'BANNER'
/* ==========================================================================
 *  AE -- a complete 32-bit operating system that boots inside a single
 *  Windows executable.
 *
 *  This file is one self-contained C translation unit.  It contains a
 *  hardware abstraction layer (Win32 is used only as bare-metal chassis),
 *  a physical memory manager, an inode based virtual file system, a
 *  preemptive process scheduler, a C-subset compiler and bytecode VM, a
 *  software compositor with a full desktop environment, and seven native
 *  applications.  No assets are external: fonts are embedded bitmaps and
 *  every pixel you see is generated by code in this file.
 *
 *  Build (MinGW-w64 gcc):
 *      gcc -O3 -std=c11 aether_os.c -o AE.exe \
 *          -lgdi32 -luser32 -lkernel32 -lwinmm -mwindows -static
 *
 *  Generated from the numbered modules in dev/ by tools/build.sh.  Those are the
 *  authoritative sources; concatenating them yields this file.
 * ========================================================================== */
BANNER

for f in "${MODULES[@]}"; do
  {
    echo
    echo "/* ======================== $f ======================== */"
    cat "$f"
  } >> aether_os.c
done

if [ "${1:-}" = "--headless" ]; then
  # gnu11 (not c11): the headless chassis uses POSIX clock_gettime/localtime_r,
  # which a strict -std=c11 hides behind feature-test macros.
  gcc -O1 -g -std=gnu11 -DAETHER_HEADLESS -Wall -Wextra -Wno-unused-parameter \
      -Wno-unused-function -Wno-sign-compare \
      aether_os.c -o dev/aether_headless -lm
  echo "built dev/aether_headless"
else
  # -Wl,--subsystem,windows == gcc's -mwindows: no console window.
  # -nostdlib keeps the C runtime out entirely: the
  # kernel supplies its own string, heap and maths routines, so the import table
  # holds nothing but kernel32/user32/gdi32/winmm.  startup.c provides the
  # loader entry point that would otherwise come from crt0.
  "$ZIG" cc -target x86_64-windows-gnu -O3 -std=c11 -Wall -Wextra \
      -Wno-unused-parameter -Wno-unused-function -Wno-sign-compare \
      aether_os.c dev/startup.c -o AE.exe \
      -nostdlib -isystem "$ZIG_LIBC" \
      -lgdi32 -luser32 -lkernel32 -lwinmm \
      -Wl,--subsystem,windows -Wl,--entry,aether_crt_entry
  echo "built AE.exe ($(stat -c%s AE.exe) bytes)"
fi
